	let language = pick(stored() || navigator.language);
	let dictionary = DICTIONARIES[language] || {};

	const format = (text, args) => text.replace(/\{\{|\}\}|\{(\d+)\}/g, (match, index) => match === "{{" ? "{" : match === "}}" ? "}" : String(args[+index]));
